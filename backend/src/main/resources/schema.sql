-- Drop tables if they exist
DROP TABLE IF EXISTS extraction_logs;
DROP TABLE IF EXISTS job_postings;
DROP TABLE IF EXISTS admins;

-- Admins Table
CREATE TABLE admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    role VARCHAR(20) DEFAULT 'ADMIN',
    last_login TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Job Postings Table
CREATE TABLE job_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    location VARCHAR(255),
    field VARCHAR(100) NOT NULL,
    conditions TEXT,
    deadline VARCHAR(100),
    method TEXT,
    expected_salary VARCHAR(100),
    source VARCHAR(20) NOT NULL, -- PDF, URL, EMAIL
    source_origin VARCHAR(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Extraction Logs Table
CREATE TABLE extraction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(20) NOT NULL,
    source_origin VARCHAR(500),
    status VARCHAR(20) NOT NULL, -- SUCCESS, FAIL
    error_message TEXT,
    extracted_data JSON,
    processed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for performance
CREATE INDEX idx_job_postings_field ON job_postings(field);
CREATE INDEX idx_job_postings_company ON job_postings(company_name);
CREATE INDEX idx_extraction_logs_status ON extraction_logs(status);
