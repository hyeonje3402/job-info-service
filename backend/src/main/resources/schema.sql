-- Drop tables if they exist
DROP TABLE IF EXISTS job_postings;
DROP TABLE IF EXISTS sources;
DROP TABLE IF EXISTS users;

-- Users Table
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL, -- ADMIN, GENERAL
    status VARCHAR(20) NOT NULL, -- ACTIVE, INACTIVE, REVOKED
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Sources Table (Previously ExtractionLog)
CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL, -- pdf, url, email
    status VARCHAR(20) NOT NULL, -- SUCCESS, FAILED
    error_message TEXT,
    extracted_data JSON,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Job Postings Table
CREATE TABLE job_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(100) NOT NULL,
    location VARCHAR(255) NOT NULL,
    position VARCHAR(100) NOT NULL,
    requirements TEXT NOT NULL,
    opening_date DATE NOT NULL,
    closing_date DATE NOT NULL,
    application_method VARCHAR(255) NOT NULL,
    expected_salary VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL, -- PENDING, APPROVED, EXPIRED
    source_id BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_job_posting_source FOREIGN KEY (source_id) REFERENCES sources(id)
);

-- Indexes for performance
CREATE INDEX idx_job_postings_position ON job_postings(position);
CREATE INDEX idx_job_postings_company ON job_postings(company_name);
CREATE INDEX idx_sources_status ON sources(status);
CREATE INDEX idx_users_email ON users(email);
