-- Drop tables if they exist
DROP TABLE IF EXISTS extraction_logs;
DROP TABLE IF EXISTS job_postings;
DROP TABLE IF EXISTS sources;
DROP TABLE IF EXISTS users;

-- Users Table
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE, -- Encrypted email can be longer
    password VARCHAR(255) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL, -- ADMIN, GENERAL
    status VARCHAR(20) NOT NULL, -- ACTIVE, INACTIVE, REVOKED
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Sources Table
CREATE TABLE sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(20) NOT NULL, -- PDF, URL, EMAIL
    reference_uri VARCHAR(500) NOT NULL, -- File path, URL, or Email ID
    status VARCHAR(20) NOT NULL, -- SUCCESS, FAILED, PROCESSING
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Extraction Logs Table
CREATE TABLE extraction_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL,
    model_version VARCHAR(50) NOT NULL,
    raw_data TEXT NOT NULL, -- JSON formatted extracted data
    processing_time_ms INTEGER NOT NULL,
    error_message TEXT,
    processed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_extraction_log_source FOREIGN KEY (source_id) REFERENCES sources(id)
);

-- Job Postings Table
CREATE TABLE job_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(100),
    location VARCHAR(255),
    position VARCHAR(100) NOT NULL,
    requirements TEXT,
    opening_date DATE,
    closing_date DATE,
    application_method VARCHAR(255),
    expected_salary VARCHAR(100),
    status VARCHAR(20) NOT NULL, -- PENDING, APPROVED, EXPIRED
    source_id BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_job_posting_source FOREIGN KEY (source_id) REFERENCES sources(id)
);

-- Indexes for performance
CREATE INDEX idx_job_postings_position ON job_postings(position);
CREATE INDEX idx_job_postings_company ON job_postings(company_name);
CREATE INDEX idx_sources_status ON sources(status);
CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_extraction_logs_source ON extraction_logs(source_id);
